"""
AI Detector
Today's challenge is inspired by the release of ChatGPT on November 30, 2022.

Given a string of one or more sentences, determine if it was likely generated by AI using the following rules:

It contains two or more dashes (-).

It contains two or more sets of parenthesis (()). Text can be within the parenthesis.

It contains three or more words with 7 or more letters.

Words are separated by a single space and only consist of letters (A-Z).
Don't include punctuation or other non-letters as part of a word.

If the given sentence meets any of the rules above, return "AI", otherwise, return "Human".

Tests:
Waiting:1. detect_ai("The quick brown fox jumped over the lazy dog.") should return "Human".
Waiting:2. detect_ai("The hypersonic brown fox - jumped (over) the lazy dog.") should return "Human".
Waiting:3. detect_ai("Yes - you're right! I made a mistake there - let me try again.") should return "AI".
Waiting:4. detect_ai("The extraordinary students were studying vivaciously.") should return "AI".
Waiting:5. detect_ai("The (excited) student was (coding) in the library.") should return "AI".
"""


def detect_ai(text):
    ai = "AI"
    human = "Human"
    # if text.count("-")>1 or text.count("("):
    #     return ai
    anamoly_count = {
        "-": 0,
        "(": 0,
        "long_word": 0
    }
    for word in text.split():
        if word in anamoly_count.keys():
            anamoly_count[word] += 1
        if len(word) > 6:
            anamoly_count["long_word"] += 1

        if anamoly_count["-"] > 1 or anamoly_count["("] > 1 or anamoly_count["long_word"] > 2 or text.isalpha():
            return ai

    return human


print(detect_ai("The quick brown fox jumped over the lazy dog"))
print(detect_ai("The hypersonic brown fox - jumped (over) the lazy dog."))
print(detect_ai("Yes - you're right! I made a mistake there - let me try again."))
print(detect_ai("The extraordinary students were studying vivaciously."))
print(detect_ai("The (excited) student was (coding) in the library."))

